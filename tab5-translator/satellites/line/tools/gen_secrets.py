#!/usr/bin/env python3
"""gen_secrets.py — write common/secrets.h (0600, gitignored) for the line satellites.

Reads, into process memory only:
  ~/.config/zenilify/t5-wifi     TAB-separated  ssid<TAB>psk  per line (landmine 335: it is NOT key=value)
  ~/.config/zenilify/papp_token  bearer
Prints lengths and counts only — never a value.

  python3 tools/gen_secrets.py [--base http://192.168.1.5:8787] [--fallback http://192.168.1.5:8788]
"""
import argparse, os, sys

ap = argparse.ArgumentParser()
ap.add_argument("--base", default="http://192.168.1.5:8787")
ap.add_argument("--fallback", default="http://192.168.1.5:8788")
a = ap.parse_args()

cfg = os.path.expanduser("~/.config/zenilify")
esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
nets = []
for line in open(os.path.join(cfg, "t5-wifi"), encoding="utf-8").read().split("\n"):
    f = line.split("\t")
    if len(f) >= 2 and f[0] and not line.startswith("#"):
        nets.append((f[0], f[1]))
tok = open(os.path.join(cfg, "papp_token"), encoding="utf-8").read().strip()
if not nets or not tok:
    sys.exit("no networks or empty token")

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "common", "secrets.h")
body = "// GENERATED by tools/gen_secrets.py — never commit, never print.\n#pragma once\n"
body += "struct LineWifi { const char *ssid; const char *psk; };\n"
body += "static const LineWifi LINE_WIFI[] = {\n" + "".join(f'  {{"{esc(s)}", "{esc(p)}"}},\n' for s, p in nets) + "};\n"
body += f'#define LINE_TOKEN "{esc(tok)}"\n#define LINE_BASE "{a.base}"\n#define LINE_FALLBACK "{a.fallback}"\n'
fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
os.write(fd, body.encode())
os.close(fd)
os.chmod(out, 0o600)
print(f"secrets.h written: networks={len(nets)} token_len={len(tok)} base={a.base} fallback={a.fallback}")
