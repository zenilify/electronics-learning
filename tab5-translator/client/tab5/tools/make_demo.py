#!/usr/bin/env python3
"""Generate the demo-mode assets (main/assets/demo/*.wav + main/demo_data.h).

Runs on cachy against the PAPP backend. For each canned phrase:
  1. POST /tts?lang=<src>&rate=16000  -> the "spoken" source utterance (Magpie TTS)
  2. POST /translate (raw audio/wav, exactly like the Tab5) -> texts + translated WAV
The source WAV is what demo mode sends through the live pipeline; the translated WAV and
texts are the offline fallback when no backend answers. The bearer is read from the 0600
file into memory only (never printed, never in argv).
"""
import json, os, sys, time, urllib.parse, urllib.request, wave, io, pathlib

BASE = os.environ.get("PAPP_URL", "http://192.168.1.5:8787")
TOKEN = open(os.path.expanduser("~/.config/zenilify/papp_token")).read().strip()
HERE = pathlib.Path(__file__).resolve().parent.parent
OUT = HERE / "main" / "assets" / "demo"
PHRASES = [  # (src, tgt, text)
    ("es", "zh", "Hola, mucho gusto. Venimos de México a visitar su empresa."),
    ("zh", "es", "欢迎来到深圳！你们想喝点茶吗？"),
    ("en", "zh", "This little screen translates between English, Spanish and Chinese."),
    ("zh", "en", "这个屏幕很清楚，声音也很好。"),
    ("es", "zh", "¿Dónde está la estación de metro más cercana?"),
]

def post(path, body, ctype):
    req = urllib.request.Request(BASE + path, data=body, method="POST",
                                 headers={"Content-Type": ctype, "Authorization": f"Bearer {TOKEN}"})
    with urllib.request.urlopen(req, timeout=90) as r:
        return r.read(), r.headers

def check16k(b):
    with wave.open(io.BytesIO(b)) as w:
        assert w.getframerate() == 16000 and w.getnchannels() == 1 and w.getsampwidth() == 2, w.getparams()
        return w.getnframes() / 16000

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for i, (src, tgt, text) in enumerate(PHRASES, 1):
        wav, _ = post(f"/tts?lang={src}&rate=16000", json.dumps({"text": text}).encode(), "application/json")
        d_src = check16k(wav)
        (OUT / f"d{i}_src.wav").write_bytes(wav)
        q = urllib.parse.urlencode({"src": src, "tgt": tgt, "format": "wav", "rate": 16000})
        t0 = time.time()
        out, h = post(f"/translate?{q}", wav, "audio/wav")
        rtt = (time.time() - t0) * 1000
        d_tgt = check16k(out)
        (OUT / f"d{i}_tgt.wav").write_bytes(out)
        st = urllib.parse.unquote(h.get("X-Papp-Src-Text", ""))
        tt = urllib.parse.unquote(h.get("X-Papp-Tgt-Text", ""))
        print(json.dumps({"i": i, "src": src, "tgt": tgt, "src_s": round(d_src, 2), "tgt_s": round(d_tgt, 2),
                          "rtt_ms": round(rtt), "asr": h.get("X-Papp-Asr-Model"), "src_text": st, "tgt_text": tt},
                         ensure_ascii=False), flush=True)
        rows.append((src, tgt, text, tt))
    lines = ["// Generated by tools/make_demo.py — do not edit. Canned demo phrases (offline fallback texts).",
             "#pragma once", "static const struct { const char *src, *tgt, *src_text, *tgt_text; } DEMO_TEXT[] = {"]
    for src, tgt, a, b in rows:
        lines.append(f"    {{{cstr(src)}, {cstr(tgt)}, {cstr(a)}, {cstr(b)}}},")
    lines += ["};", f"#define DEMO_COUNT {len(rows)}", ""]
    (HERE / "main" / "demo_data.h").write_text("\n".join(lines), encoding="utf-8")

if __name__ == "__main__":
    sys.exit(main())
