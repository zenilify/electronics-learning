#!/usr/bin/env python3
"""Write placeholder secrets so firmware compiles without any real credential.

  dummy_secrets.py esphome <dir>...   -> <dir>/secrets.yaml for every !secret used there
  dummy_secrets.py header  <secrets.h.example> <out secrets.h>

Values are deterministic (derived from the key name) so builds are reproducible,
and every string carries 'foundry' so a dummy image is recognisable on sight.
They are shaped to pass ESPHome validation (32-byte base64 API keys, >= 8 char
AP passwords).
"""
import base64, hashlib, pathlib, re, sys


def value(key: str) -> str:
    k = key.lower()
    h = hashlib.sha256(("foundry:" + key).encode()).digest()
    if "encryption" in k or k.endswith("api_key") or k == "api_key":
        return base64.b64encode(h).decode()          # 32 bytes, valid noise PSK
    if "ssid" in k:
        return "foundry-dummy-ssid"
    if "password" in k or "pass" in k:
        return "foundry-" + h.hex()[:12]
    if "auth" in k:
        return "Basic " + base64.b64encode(b"foundry:dummy").decode()
    if "token" in k:
        return "foundry-dummy-token-" + h.hex()[:16]
    return "foundry-dummy"


def esphome(dirs):
    for d in map(pathlib.Path, dirs):
        keys = set()
        for y in d.glob("*.yaml"):
            if y.name == "secrets.yaml" or y.name.startswith("._"):
                continue
            keys |= set(re.findall(r"!secret\s+([A-Za-z0-9_]+)", y.read_text()))
        out = d / "secrets.yaml"
        out.write_text("# generated by foundry/scripts/dummy_secrets.py - placeholders only\n" +
                       "".join(f'{k}: "{value(k)}"\n' for k in sorted(keys)))
        print(f"{out}: {len(keys)} placeholder keys")


def header(src, dst):
    text = pathlib.Path(src).read_text()
    def sub(m):
        return f'#define {m.group(1)} "{value(m.group(1))}"'
    text = re.sub(r'#define\s+(\w+)\s+"[^"]*"', sub, text)
    pathlib.Path(dst).write_text("// generated by foundry - placeholders only\n" + text)
    print(f"{dst}: placeholders from {src}")


if __name__ == "__main__":
    if sys.argv[1] == "esphome":
        esphome(sys.argv[2:])
    elif sys.argv[1] == "header":
        header(sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)
